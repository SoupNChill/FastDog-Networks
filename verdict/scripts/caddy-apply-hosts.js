#!/usr/bin/env node
/**
 * Generate reviewable Caddy snippets only. Validation/reload is operator-owned.
 */
import { mkdir } from 'node:fs/promises';
import { writeConfig } from '../src/config/files.js';
import { join } from 'node:path';
import { createHostStore, isEnforceDenied, ENFORCE_DENYLIST } from '../src/config/hosts.js';

const apply = process.argv.includes('--apply');
if (apply) throw new Error('Automatic apply disabled: review generated snippets and validate/reload Caddy manually');
const hostsFile = process.env.VERDICT_HOSTS_FILE || 'data/hosts.json';
const outDir = process.env.VERDICT_CADDY_SNIPPET_DIR || 'data/caddy-generated';
const includeName = 'verdict-hosts.caddy';

const store = createHostStore(hostsFile);
await store.load();
const hosts = store.list().filter(h => h.enable && h.mode === 'enforce');

function snippetFor(h) {
  if (isEnforceDenied(h.host)) return '';
  const failOpen = h.fail !== 'closed';
  return `
# generated by verdict caddy-apply-hosts — do not hand-edit
${h.host} {
	encode gzip
	@exempt path /challenge /challenge/* /branding/*
	handle @exempt {
		reverse_proxy 127.0.0.1:8089 {
			header_up X-Forwarded-Host {host}
			header_up X-Forwarded-For {remote_host}
			header_up -X-Real-IP
		}
	}
	handle {
		route {
			vars verdict_auth_pending yes
			forward_auth 127.0.0.1:8089 {
				uri /v1/edge-auth
				header_up X-Forwarded-Host {host}
				header_up X-Forwarded-For {remote_host}
				header_up -X-Real-IP
				header_up -X-Verdict-Demo
				header_up -X-Verdict-Force
				copy_headers X-Verdict-Action
				transport http {
					dial_timeout 50ms
					response_header_timeout 200ms
				}
				@challenge status 401
				handle_response @challenge {
					redir {rp.header.Location} 303
				}
				@block status 403
				handle_response @block {
					respond "Blocked by Verdict" 403
				}
			}
			vars verdict_auth_pending no
			# upstream reverse_proxy is operator-owned; placeholder respond for validate-only
			respond "Verdict enforce placeholder — set upstream" 200
		}
	}
	handle_errors {
		@authUnavailable expression \`{http.vars.verdict_auth_pending} == "yes" && {http.error.status_code} >= 500\`
		handle @authUnavailable {
${failOpen ? '			header X-Verdict-Fail-Open true\n			respond "Verdict: auth unavailable, request allowed" 200' : '			respond "Verdict unavailable" 503'}
		}
		handle {
			respond "Error" {http.error.status_code}
		}
	}
}
`.trim() + '\n';
}

await mkdir(outDir, { recursive: true });
const body = [
  `# Auto-generated ${new Date().toISOString()}`,
  `# Denylist (never enforce): ${ENFORCE_DENYLIST.join(', ')}`,
  ...hosts.map(snippetFor).filter(Boolean),
].join('\n');
const outPath = join(outDir, includeName);
await writeConfig(outPath, body || '# no enforce hosts\n');
console.log(JSON.stringify({ wrote: outPath, enforce_hosts: hosts.map(h => h.host), dry_run: !apply }));
